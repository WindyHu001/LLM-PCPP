#!/usr/bin/env python
"""Ask an LLM for points of interest (POIs) on a scene's semantic grid map.

The POIs used in the paper are stored in configs/ (they were produced
interactively with ChatGPT). Use this script to generate POIs for a new map:

    export OPENAI_API_KEY=...
    python scripts/identify_pois.py --config configs/my_site.yaml --num-pois 12 --output configs/my_site_pois.yaml
    python scripts/identify_pois.py --config configs/exp3_indoor_warehouse.yaml --num-pois 13 --model o1 \\
        --guidance "Ensure detailed exploration around the cold storage area."

POIs outside the map or inside an obstacle are discarded. Without --output the
POIs are printed as YAML that can be pasted into a config.
"""

from __future__ import annotations

import argparse
import sys
from datetime import date
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))  # allow running from a source checkout without installing

from llm_pcpp import OpenAIChatModel, load_scene  # noqa: E402
from llm_pcpp.llm import is_reasoning_model  # noqa: E402
from llm_pcpp.poi import identify_pois  # noqa: E402


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__.split("\n\n")[0],
        epilog=__doc__.split("\n\n", 1)[1],
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--config", type=Path, required=True, help="scene config (YAML)")
    parser.add_argument("--num-pois", type=int, default=12, help="number of POIs to request (default: 12)")
    parser.add_argument("--model", default="gpt-4o", help="OpenAI model (default: gpt-4o)")
    parser.add_argument("--guidance", default=None,
                        help="task guidance (default: task_guidance from the config)")
    parser.add_argument("--output", type=Path, default=None,
                        help="write a copy of the config with the new POIs to this file")
    args = parser.parse_args(argv)

    scene = load_scene(args.config)
    max_tokens = 16000 if is_reasoning_model(args.model) else 2000
    model = OpenAIChatModel(args.model, max_tokens=max_tokens, stop=None)
    try:
        valid, rejected, answer = identify_pois(scene, model, args.num_pois, args.guidance)
    except RuntimeError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    print(f"{len(valid)} valid POIs, {len(rejected)} rejected (outside the map, inside an obstacle or duplicated)")
    for poi in rejected:
        print(f"  rejected ({poi.x}, {poi.y}) {poi.note}")
    pois = [{"name": p.name, "x": p.x, "y": p.y, "note": p.note} for p in valid]

    if args.output is None:
        print(yaml.safe_dump({"pois": pois}, sort_keys=False, allow_unicode=True, width=120, default_flow_style=None))
        return 0

    with args.config.open("r", encoding="utf-8") as f:
        data = yaml.safe_load(f)
    data["pois"] = pois
    data.pop("paper_results", None)
    header = (
        f"# POIs generated by scripts/identify_pois.py with {args.model} on {date.today()}\n"
        f"# from {args.config}. Review them before use.\n"
    )
    args.output.write_text(header + yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=120, default_flow_style=None))
    print(f"Wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
